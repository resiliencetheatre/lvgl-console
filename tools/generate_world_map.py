#!/usr/bin/env python3
"""Generate compact line segments from Natural Earth 110m country GeoJSON.
Source (public domain): https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_admin_0_countries.geojson
Usage: python3 tools/generate_world_map.py countries.geojson > src/world_map_data.h
"""
import json
import sys


def simplify(points, tolerance=0.6):
    if len(points) <= 2:
        return points
    ax, ay = points[0]
    bx, by = points[-1]
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    def distance(p):
        t = max(0, min(1, ((p[0]-ax)*dx + (p[1]-ay)*dy)/length)) if length else 0
        return (p[0]-ax-t*dx)**2 + (p[1]-ay-t*dy)**2
    index = max(range(1, len(points)-1), key=lambda i: distance(points[i]))
    if distance(points[index]) <= tolerance*tolerance:
        return [points[0], points[-1]]
    return simplify(points[:index+1], tolerance)[:-1] + simplify(points[index:], tolerance)

segments = set()
with open(sys.argv[1]) as source:
    data = json.load(source)
for feature in data['features']:
    if feature['properties'].get('ADMIN') == 'Antarctica':
        continue
    geometry = feature['geometry']
    polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    for polygon in polygons:
        ring = polygon[0]  # exterior only; omit small internal lakes
        points = simplify(ring)
        for a, b in zip(points, points[1:]):
            if abs(a[0]-b[0]) > 180:  # do not connect across the map at the dateline
                continue
            a = tuple(round(v*10) for v in a)
            b = tuple(round(v*10) for v in b)
            if a != b:
                segments.add(tuple(sorted((a, b))))
print('/* Generated by tools/generate_world_map.py; Natural Earth public-domain data. */')
print('static const int16_t world_segments[][4] = {')
for a, b in sorted(segments):
    print('    {%d, %d, %d, %d},' % (*a, *b))
print('};')
